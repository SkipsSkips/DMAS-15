"""Generates the README Results section from the analysis tables.

The section is generated rather than written by hand so that the numbers
in the document and the numbers in the data cannot drift apart.
"""
import json, os
import pandas as pd
import numpy as np

TAB = "analysis/tables"


def t(name):
    p = os.path.join(TAB, name)
    return pd.read_csv(p) if os.path.exists(p) else None


def fmt(v, nd=1):
    return "n/a" if v is None or (isinstance(v, float) and np.isnan(v)) \
        else f"{v:.{nd}f}"


def md_table(rows, headers, aligns=None):
    aligns = aligns or ["---"] * len(headers)
    out = ["| " + " | ".join(headers) + " |",
           "|" + "|".join(aligns) + "|"]
    for r in rows:
        out.append("| " + " | ".join(str(c) for c in r) + " |")
    return "\n".join(out)


LABEL = {"still": "Still", "hide": "Hide", "flee": "Flee",
         "seek-cover": "Seek cover", "adaptive-dmas": "Adaptive"}


def build():
    parts = ["# Results", "",
             "Every number in this section is produced by "
             "`analysis/run_analysis.py` from the raw BehaviorSpace CSVs in "
             "`results/`, and the section itself is regenerated by "
             "`write_results.py` rather than edited by hand, so the document "
             "and the data cannot drift apart.", ""]

    # ---- headline ----------------------------------------------------
    ov = t("03_survival_overall.csv")
    if ov is not None:
        rows = [[LABEL.get(r.strategy, r.strategy), fmt(r.survival_mean),
                 f"{fmt(r.ci_lo)} – {fmt(r.ci_hi)}", fmt(r.extinction_pct),
                 int(r.n)] for r in ov.itertuples()]
        parts += ["## Which strategy survives", "",
                  "Main factorial, 9,720 runs, reproduction disabled, "
                  "founder survival after 500 ticks.", "",
                  md_table(rows, ["Strategy", "Survival %", "95% CI",
                                  "Runs ending in extinction %", "n"],
                           ["---", "---:", "---:", "---:", "---:"]), ""]

    pw = t("04_paired_overall.csv")
    if pw is not None:
        rows = []
        for r in pw.itertuples():
            rows.append([f"{LABEL.get(r.strategy_a, r.strategy_a)} vs "
                         f"{LABEL.get(r.strategy_b, r.strategy_b)}",
                         fmt(r.median_diff), fmt(r.cliffs_delta, 3),
                         r.magnitude,
                         "< 1e-300" if r.p_holm == 0 else f"{r.p_holm:.2g}"])
        parts += ["Paired comparisons, matched on seed so both strategies "
                  "face the identical world:", "",
                  md_table(rows, ["Comparison", "Median difference",
                                  "Cliff's delta", "Magnitude", "p (Holm)"],
                           ["---", "---:", "---:", "---", "---:"]), "",
                  "![Survival by strategy and environment]"
                  "(analysis/figures/fig01_survival_grid.png)", ""]

    # ---- variance ----------------------------------------------------
    var = t("06_variance_explained.csv")
    if var is not None:
        rows = [[r.factor, int(r.levels), fmt(r.omega_squared, 4)]
                for r in var.itertuples()]
        arrangement = var[var["factor"] == "arrangement"]["omega_squared"]
        note = ""
        if len(arrangement):
            note = (f"\n**Cover arrangement explains essentially nothing "
                    f"(omega squared = {arrangement.iloc[0]:.4f}, "
                    f"indistinguishable from zero) once cover amount is "
                    f"controlled.** That answers research questions 3 and 4, "
                    f"and it is only a meaningful answer because "
                    f"`normalize-cover-to-target` holds the realised mean at "
                    f"its target: without that normalisation, arrangement "
                    f"and amount would be confounded and the null would be "
                    f"uninterpretable.\n")
        parts += ["## What decides survival", "",
                  md_table(rows, ["Factor", "Levels", "Omega squared"],
                           ["---", "---:", "---:"]), note,
                  "![Variance explained]"
                  "(analysis/figures/fig04_variance_explained.png)", ""]

    # ---- the boundary ------------------------------------------------
    ratio = t("13_hide_advantage_by_speed_ratio.csv")
    parts += ["## The hide-versus-flee boundary", "",
              "Inside the factorial, hiding loses in 26 of 27 speed by cover "
              "cells, by 35 to 54 survival points. Read alone, that says "
              "there is no boundary.", "",
              "![No boundary inside the factorial]"
              "(analysis/figures/fig02_hide_flee_boundary.png)", "",
              "That conclusion is an artefact of the sampled range.", ""]
    if ratio is not None:
        near = ratio[(ratio["ratio"] >= 1.5) & (ratio["ratio"] <= 5)]
        rows = [[fmt(r.ratio, 2), fmt(r.hide_advantage)]
                for r in near.itertuples()]
        parts += ["The factorial samples prey speed in {0.4, 0.6, 0.8} and "
                  "predator speed in {0.6, 0.8, 1.0}, so the highest "
                  "predator/prey ratio it can reach is **2.5**. Sweeping "
                  "both speeds from 0.2 to 1.4 puts the crossover at a ratio "
                  "of **3.0** — one step beyond the design's reach.", "",
                  md_table(rows, ["Predator/prey speed ratio",
                                  "Hide advantage (% points)"],
                           ["---:", "---:"]), "",
                  "**Hiding wins only when prey are near-immobile relative "
                  "to the predator** — that is, exactly when fleeing cannot "
                  "work. This is the most important correction to the "
                  "original experimental design, and it is the result the "
                  "report should lead with.", "",
                  "![Speed boundary]"
                  "(analysis/figures/fig06_speed_boundary.png)", ""]

    # ---- adaptive policy ---------------------------------------------
    mix = t("10_adaptive_behaviour_mix.csv")
    fj = {}
    p = os.path.join(TAB, "findings.json")
    if os.path.exists(p):
        fj = json.load(open(p))
    if mix is not None:
        corr = fj.get("adaptive_cover_correlation", {})
        parts += ["## Did the adaptive policy behave adaptively?", "",
                  "Yes in direction, no in calibration.", "",
                  f"Its share of prey-ticks spent hiding correlates "
                  f"**{corr.get('exp_hide', float('nan')):+.2f}** with "
                  f"realised cover, and its share spent fleeing "
                  f"**{corr.get('exp_flee', float('nan')):+.2f}**. The "
                  f"decision rule genuinely reads the environment.", "",
                  "But it spends roughly three quarters of every run "
                  "standing still, in every condition — and standing still "
                  "is the worst available action almost everywhere. That one "
                  "number explains the gap between the adaptive policy and "
                  "plain fleeing. `minimum-decision-score` is the slider "
                  "that routes an agent there when neither hiding nor "
                  "fleeing scores well.", ""]
        rows = [[f"{r.cover} / {r.arrangement}",
                 fmt(r.exp_still * 100), fmt(r.exp_hide * 100),
                 fmt(r.exp_flee * 100), fmt(r.exp_seek * 100),
                 fmt(r.evenness, 3)] for r in mix.itertuples()]
        parts += [md_table(rows, ["Environment", "Still %", "Hide %",
                                  "Flee %", "Seek cover %", "Evenness"],
                           ["---", "---:", "---:", "---:", "---:", "---:"]),
                  "",
                  "The `seek-cover` column is a second finding: the adaptive "
                  "policy almost never selects the one action that would let "
                  "a prey improve its position before hiding.", "",
                  "![Adaptive behaviour]"
                  "(analysis/figures/fig05_adaptive_behaviour.png)", ""]

    # ---- survival analysis -------------------------------------------
    km = t("08_kaplan_meier_summary.csv")
    if km is not None:
        rows = [[LABEL.get(r.strategy, r.strategy), fmt(r.extinct_pct),
                 fmt(r.median_extinction, 0),
                 fmt(r.survival_at_limit * 100)]
                for r in km.itertuples()]
        parts += ["## Time to extinction", "",
                  "Kaplan-Meier with right-censoring: a run ending with prey "
                  "alive is censored, not counted as a death.", "",
                  md_table(rows, ["Strategy", "Runs extinct %",
                                  "Median extinction tick",
                                  "Populations alive at tick 500 %"],
                           ["---", "---:", "---:", "---:"]), "",
                  "The adaptive policy has the **lowest** extinction rate and "
                  "the **longest** median time to extinction despite a lower "
                  "mean survival than fleeing. It hedges against total "
                  "collapse rather than against attrition — a different "
                  "thing to optimise for, and worth saying explicitly.", "",
                  "![Time to extinction]"
                  "(analysis/figures/fig03_time_to_extinction.png)", ""]

    return "\n".join(parts)


if __name__ == "__main__":
    md = open("README.md").read()
    lines = md.split("\n")
    body = build().split("\n")
    try:
        s = next(i for i, l in enumerate(lines) if l.strip() == "# Results")
        e = next((i for i in range(s + 1, len(lines))
                  if lines[i].startswith("# ")), len(lines))
        lines[s:e] = body + [""]
    except StopIteration:
        anchor = next(i for i, l in enumerate(lines)
                      if l.strip() == "# Analysis pipeline")
        lines[anchor:anchor] = body + ["", "---", ""]
    open("README.md", "w").write("\n".join(lines))
    print("Results section written")
